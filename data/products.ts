export interface UserProfile {
  sexe: string;
  taille: number;
  poids: number;
  largeurPied: string;
  foulee: string;
  niveau: string;
  distance: string;
  terrain: string;
  objectif: string;
  blessures: string;
  dropPreference: string;
  amortPreference: string;
  // Champs optionnels — enrichissement progressif
  budget?: string;          // '<100' | '100-140' | '140-180' | '180+'
  voutePlantaire?: string;  // 'plat' | 'normale' | 'creux' | 'inconnu'
  volume?: string;          // '0-10' | '10-25' | '25-50' | '50+'
}

export interface Recommendation {
  product: Product;
  score: number;
  reasons: string[];
}

export function getRecommendations(
  profile: UserProfile,
  limit = 3,
  sourceProducts: Product[] = products
): Recommendation[] {
  // Filtre budget avant scoring (garde au moins 5 modèles)
  let candidateProducts = sourceProducts
  if (profile.budget) {
    const inBudget = sourceProducts.filter((p) => {
      if (profile.budget === '<100')    return p.prix < 100
      if (profile.budget === '100-140') return p.prix >= 100 && p.prix <= 140
      if (profile.budget === '140-180') return p.prix > 140 && p.prix <= 180
      if (profile.budget === '180+')    return p.prix > 180
      return true
    })
    if (inBudget.length >= 5) candidateProducts = inBudget
  }

  const scored = candidateProducts.map((product) => {
    let score = 0;
    const reasons: string[] = [];

    // Foulée match (most important)
    if (product.foulee.includes(profile.foulee as any)) {
      score += 30;
      const fouleeLabel = profile.foulee === "pronateur" ? "stabilité" : profile.foulee === "supinateur" ? "amorti renforcé" : "universalité";
      reasons.push(`Adaptée à votre foulée ${profile.foulee} — ${fouleeLabel}`);
    }

    // Terrain match
    if (product.terrain.includes(profile.terrain as any)) {
      score += 20;
      reasons.push(`Conçue pour le ${profile.terrain}`);
    } else if (product.terrain.includes("mixte")) {
      score += 8;
      reasons.push("Polyvalente tous terrains");
    }

    // Niveau match
    if (product.niveau.includes(profile.niveau as any)) {
      score += 12;
      reasons.push(`Adaptée au niveau ${profile.niveau}`);
    }

    // Objectif match
    if (product.objectif.includes(profile.objectif as any)) {
      score += 12;
      reasons.push(`Optimisée pour : ${profile.objectif}`);
    }

    // Largeur pied match
    if (product.largeurDisponible.includes(profile.largeurPied as any)) {
      score += 8;
      reasons.push(`Disponible en largeur ${profile.largeurPied}`);
    }

    // Drop preference
    if (profile.dropPreference === "faible" && product.drop <= 6) {
      score += 8;
      reasons.push(`Drop faible (${product.drop}mm) — foulée naturelle`);
    } else if (profile.dropPreference === "élevé" && product.drop >= 10) {
      score += 8;
      reasons.push(`Drop élevé (${product.drop}mm) — amorti talon`);
    } else if (profile.dropPreference === "moyen" && product.drop > 6 && product.drop < 10) {
      score += 8;
      reasons.push(`Drop moyen (${product.drop}mm) — polyvalent`);
    }

    // Amorti preference
    if (profile.amortPreference && product.amorti === profile.amortPreference) {
      score += 8;
      reasons.push(`Niveau d'amorti ${product.amorti} correspondant`);
    }

    // Blessures → prévention bonus
    if (profile.blessures === "oui" && product.objectif.includes("prévention")) {
      score += 10;
      reasons.push("Recommandée pour la prévention des blessures");
    }
    if (profile.blessures === "oui" && product.stabilite === "élevée") {
      score += 5;
      reasons.push("Stabilité renforcée pour protéger vos articulations");
    }

    // Voûte plantaire
    if (profile.voutePlantaire && profile.voutePlantaire !== 'inconnu') {
      if (profile.voutePlantaire === 'plat' && product.stabilite === 'élevée') {
        score += 15;
        reasons.push('Stabilité renforcée — idéale pour pied plat');
      } else if (profile.voutePlantaire === 'creux' && product.amorti === 'élevé') {
        score += 15;
        reasons.push('Amorti élevé — adapté au pied creux');
      } else if (profile.voutePlantaire === 'normale') {
        score += 5;
      }
    }

    // Volume d'entraînement
    if (profile.volume === '25-50' || profile.volume === '50+') {
      if (product.amorti !== 'faible') {
        score += 8;
        reasons.push("Durabilité adaptée à ton volume d'entraînement");
      }
    }

    // Distance bonus
    if (
      (profile.distance === "marathon" || profile.distance === "ultra") &&
      product.amorti === "élevé"
    ) {
      score += 8;
      reasons.push("Amorti renforcé pour longues distances");
    }
    if (
      (profile.distance === "5km" || profile.distance === "10km") &&
      product.poids < 250
    ) {
      score += 8;
      reasons.push("Légèreté idéale pour les distances courtes");
    }

    return { product, score, reasons };
  });

  const minScore = limit > 5 ? 5 : 25;
  const filtered = scored
    .filter((r) => r.score >= minScore)
    .sort((a, b) => b.score - a.score);

  // Always return up to `limit` results (take best matches even if below threshold)
  const result = filtered.length >= limit ? filtered : scored.sort((a, b) => b.score - a.score);
  return result.slice(0, limit);
}
